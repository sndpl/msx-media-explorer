//! Canonical MSX-DOS boot blocks (sector 0 templates).
//!
//! The two 512-byte images are ports of openMSX `src/fdc/BootBlocks.cc`
//! (GPL-2.0, © the openMSX team), which captured them from real hardware: the
//! DOS 1 block from a Philips NMS 8250 formatting a disk, the DOS 2 block from
//! the same machine running MSX-DOS 2.20. They contain the Z80 boot loader that
//! chain-loads `MSXDOS.SYS`; the system files themselves are copyrighted and
//! are never embedded.
//!
//! Both templates carry a 720KB BPB, which [`super::write::set_boot_block`]
//! replaces with the target disk's own BPB — only the code region is installed.

